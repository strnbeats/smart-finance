import json

from backend.llm_client import GigaChatClient


def build_expense_analysis_prompt(summary: dict) -> str:
    """Создаёт запрос к модели на основе агрегированных финансовых данных."""

    total_expenses = summary["total_expenses"]

    categories = []

    for category, amount_kopeks in summary["expenses_by_category"].items():
        share = (
            round(amount_kopeks / total_expenses * 100, 2)
            if total_expenses > 0
            else 0
        )

        categories.append(
            {
                "category": category,
                "amount_rub": round(amount_kopeks / 100, 2),
                "share_percent": share,
            }
        )

    categories.sort(
        key=lambda item: item["amount_rub"],
        reverse=True,
    )

    data = {
        "period": {
            "start_date": summary["start_date"],
            "end_date": summary["end_date"],
        },
        "currency": "RUB",
        "total_income_rub": round(summary["total_income"] / 100, 2),
        "total_expenses_rub": round(total_expenses / 100, 2),
        "balance_rub": round(summary["balance"] / 100, 2),
        "transactions_count": summary["transactions_count"],
        "expenses_by_category": categories,
    }

    return f"""
Ты — AI-аналитик личных финансов в приложении Smart Finance.

Проанализируй финансовую сводку и подготовь полезный, понятный
отчёт на русском языке.

## Правила анализа

1. Используй только сведения из переданной сводки.
2. Все денежные суммы уже указаны в рублях. Не переводить их
   в копейки и не пересчитывать повторно.
3. Доли расходов по категориям уже рассчитаны программой.
   Используй переданные значения без повторного расчёта.
4. Не придумывай покупки, доходы, финансовые цели, привычки,
   подписки, долги и обстоятельства пользователя.
5. Не называй расходы чрезмерными или проблемными без информации
   о бюджете и потребностях пользователя.
6. Не делай выводов о росте или снижении расходов: перед тобой
   только один период.
7. Не путай доходы, расходы и баланс. Не изменяй переданные суммы.
8. Не повторяй одну и ту же мысль в нескольких разделах.
9. Не используй расплывчатые рекомендации вроде «меньше трать»
   или «лучше управляй финансами».
10. Рекомендации должны быть проверяемыми и опираться на данные.
    Если сводка не позволяет предложить конкретные способы экономии,
    честно укажи это вместо выдуманных советов.
11. Не представляй возможную экономию как гарантированный результат.
12. Не запрашивай личные или банковские данные.

## Формат ответа

Используй Markdown и следующие разделы:

### Краткий вывод
Два-три предложения о доходах, расходах и балансе за период.
Не повторяй все цифры без объяснения их смысла.

### Структура расходов
Перечисли основные категории в порядке убывания суммы.
Для каждой укажи сумму в рублях и долю в процентах.
При небольшом количестве категорий перечисли их все.

### Что показывают данные
Приведи от одного до трёх конкретных наблюдений.
Например, можно отметить, что определённые категории составляют
значительную часть расходов. Не называй это проблемой без оснований.

### Что можно проверить
Предложи от двух до четырёх практических действий, только если
данные дают основания для полезных рекомендаций.
Например, можно предложить проверить состав крупнейшей категории
или сравнить расходы с личным бюджетом.
Не утверждай, что в категории есть лишние покупки: детализации
отдельных покупок во входных данных нет.

### Ограничения анализа
Кратко укажи, какие выводы нельзя сделать по агрегированной
сводке. Не перечисляй ограничения, несущественные для результата.

Если данных мало, явно сообщи об этом и сократи отчёт.
Не заполняй разделы общими фразами ради соблюдения шаблона.

Финансовые данные:
{json.dumps(data, ensure_ascii=False, indent=2)}
""".strip()


def analyze_expenses(summary: dict) -> str:
    """Передаёт агрегированную сводку GigaChat и возвращает анализ."""

    if summary["total_expenses"] <= 0:
        return (
            "За выбранный период расходы не зарегистрированы. "
            "Недостаточно данных для анализа структуры расходов. "
            "Проверь, что операции за этот период импортированы."
        )

    client = GigaChatClient()
    prompt = build_expense_analysis_prompt(summary)

    return client.ask(prompt)