def category_from_mcc(mcc: str | int | None) -> str | None:
    """Возвращает категорию по MCC-коду или None, если код неизвестен."""
    if mcc is None:
        return None

    normalized_mcc = str(mcc).strip()

    if len(normalized_mcc) != 4 or not normalized_mcc.isdigit():
        return None

    return MCC_CATEGORIES.get(normalized_mcc)